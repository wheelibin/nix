local function script(name)
	return os.getenv("HOME") .. "/.config/rex/" .. name
end

-- Runs a command in a floating pane over the current session, closing when it exits.
-- rex-float closes the layer itself so focus returns to the pane you came from.
local function float(session_id, command, bounds, cwd)
	local _, err = rex.session.new_layer({
		session_id = session_id,
		bounds = bounds,
		focus = true,
		layout = rex.layout.block({
			flavor = "com.superlogical.terminal.shell",
			options = { command = { script("rex-float"), unpack(command) }, cwd = cwd },
		}),
	})
	if err ~= nil then
		error(err, 0)
	end
end

