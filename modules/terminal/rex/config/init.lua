	run = function(ctx, args)
		rex.client.queue("client.theme.import", { path = os.getenv("HOME") .. "/.config/rex/theme" })
	end,
})

-- smart-splits: alt+m/n/e/i move between Rex panes, and pass through to nvim/tmux so
-- smart-splits there moves between its windows and hands off to Rex at the edge.
-- Loads the Rex half of the backend from the checkout lazy.nvim installs.
local splits_path = os.getenv("HOME") .. "/.local/share/nvim/lazy/smart-splits-backend-rex/rex/?.lua"
local ok, splits = pcall(function()
	package.path = splits_path .. ";" .. package.path
	return require("smart-splits-backend-rex")
end)
if ok then
	for key, direction in pairs({ m = "left", n = "down", e = "up", i = "right" }) do
		rex.bind("alt+" .. key, splits.focus(direction))
	end
else
	rex.log("warn", "smart-splits-backend-rex not found; open nvim once so lazy.nvim installs it, then reload")
end
